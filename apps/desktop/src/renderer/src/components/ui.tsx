/**
 * The app's shared primitives under their short names. The components themselves are shadcn/ui's
 * (components/ui/, generated by the CLI and never edited, so `shadcn add` can refresh them); this
 * file adapts them to the names, sizes and look the rest of the renderer already uses, and adds
 * what shadcn does not have (a reason on a disabled menu item).
 */

type Variant = 'default' | 'primary' | 'danger' | 'ghost'

// The app's four button kinds, on shadcn's variants (same colour names, so there is little to
// override): default = a bordered secondary, primary = the one blue button, danger, ghost.
const buttonLook: Record<Variant, { variant: 'secondary' | 'default' | 'destructive' | 'ghost'; className: string }> = {
  default: { variant: 'secondary', className: 'border border-border hover:bg-accent hover:text-accent-foreground' },
  primary: { variant: 'default', className: '' },
  danger: { variant: 'destructive', className: 'dark:bg-destructive' },
  ghost: { variant: 'ghost', className: 'text-muted-foreground hover:text-foreground dark:hover:bg-accent' },
}

export function Button({ variant = 'default', size = 'md', className, ...props }: ButtonHTMLAttributes<HTMLButtonElement> & { variant?: Variant; size?: 'sm' | 'md'; ref?: React.Ref<HTMLButtonElement> }) {
  const look = buttonLook[variant]
  return (
    <ShadButton
      variant={look.variant}
      size={size === 'sm' ? 'xs' : 'sm'}
      className={cn(size === 'md' && 'text-sm', look.className, className)}
      {...props}
    />
  )
}

export function Kbd({ children }: { children: ReactNode }) {
  return <ShadKbd className="h-auto min-w-0 rounded border border-border bg-card px-1 py-px font-mono text-2xs font-normal text-muted-foreground">{children}</ShadKbd>
}

/**
 * A tooltip around one element: `<WithTooltip text="Push"><button/></WithTooltip>`. No text, no tooltip.
 * It closes on any press anywhere: while a Radix menu is open the page's pointer events are off,
 * so the trigger would never see its pointer leave and the tooltip would sit on top of the menu.
 */
export function WithTooltip({ text, children, side, delay }: { text?: string; children: ReactNode; side?: 'top' | 'bottom' | 'left' | 'right'; delay?: number }) {
  const [open, setOpen] = useState(false)
  useEffect(() => {
    if (!open) return
    const close = () => setOpen(false)
    window.addEventListener('pointerdown', close, true)
    return () => window.removeEventListener('pointerdown', close, true)
  }, [open])
  if (!text) return <>{children}</>
  return (
    <Tooltip open={open} onOpenChange={setOpen} delayDuration={delay}>
      <TooltipTrigger asChild>{children}</TooltipTrigger>
      <TooltipContent side={side}>{text}</TooltipContent>
    </Tooltip>
  )
}

/**
 * An icon-only toolbar button. The label is its accessible name and (unless a richer title is
 * given) its tooltip, so screen readers and tests still see "Push", not an arrow.
 */
export function ToolbarButton({ icon, label, onClick, disabled, title, badge, className }: {
  icon: ReactNode; label: string; onClick?: () => void; disabled?: boolean; title?: string; badge?: ReactNode; className?: string
}) {
  return (
    <WithTooltip text={title ?? label} side="bottom">
      <button
        onClick={onClick}
        disabled={disabled}
        aria-label={label}
        className={cn('no-drag relative flex size-8 shrink-0 items-center justify-center rounded-md text-muted-foreground hover:bg-accent hover:text-foreground disabled:pointer-events-none disabled:opacity-40', className)}
      >
        {icon}
        {badge}
      </button>
    </WithTooltip>
  )
}

export function Spinner({ className }: { className?: string }) {
  return <span className={cn('inline-block size-3 animate-spin rounded-full border-2 border-current border-t-transparent', className)} />
}

/** The look of every section header: sentence case, 12 px medium, muted. Not uppercase: it is a label, not a shout. */
export const sectionHeaderClass = 'text-xs font-medium text-muted-foreground'

/**
 * The one section header. `count` is a muted suffix ("Unstaged 3"), `right` is a slot for the
 * section's own actions, `as` lets a heading be a real heading for screen readers, and
 * `className` adjusts the padding where a header sits in a narrower surface.
 */
export function SectionHeader({ children, count, right, as: Tag = 'div', className }: {
  children: ReactNode; count?: number | string; right?: ReactNode; as?: 'div' | 'h2' | 'h3'; className?: string
}) {
  return (
    <Tag className={cn('flex h-row-lg items-center justify-between gap-2 px-3', sectionHeaderClass, className)}>
      <span className="truncate">
        {children}
        {count !== undefined && <span className="ml-1.5 font-normal text-hint">{count}</span>}
      </span>
      {right}
    </Tag>
  )
}

/**
 * Why an item is greyed out. shadcn's items set pointer-events: none when disabled, so the
 * tooltip hangs on a wrapper around the item, which still sees the pointer.
 */
function Reason({ reason, children }: { reason?: string; children: ReactNode }) {
  if (!reason) return <>{children}</>
  return (
    <Tooltip>
      <TooltipTrigger asChild><div>{children}</div></TooltipTrigger>
      <TooltipContent side="right">{reason}</TooltipContent>
    </Tooltip>
  )
}

const itemText = 'h-row-lg py-0 text-sm'

export const CM = {
  // No animation, like a native menu. Opening: shadcn slides the menu in from the left, so for its
  // first ~100ms it sits under the cursor, and the button release of the right-click that opened it
  // picks an item. Closing: the menu would linger (and block the page's pointer) for its fade-out.
  Content: ({ children }: { children: ReactNode }) => <ContextMenuContent className="min-w-48 data-[state=open]:animate-none! data-[state=closed]:animate-none!">{children}</ContextMenuContent>,
  /** `reason` greys the item out and says why on hover (a tooltip, and aria-description). */
  Item: ({ children, onSelect, disabled, danger, reason }: { children: ReactNode; onSelect: () => void; disabled?: boolean; danger?: boolean; reason?: string }) => (
    <Reason reason={reason}>
      <ContextMenuItem className={itemText} variant={danger ? 'destructive' : 'default'} onSelect={onSelect} disabled={disabled || !!reason} aria-description={reason}>
        {children}
      </ContextMenuItem>
    </Reason>
  ),
  Separator: () => <ContextMenuSeparator />,
  Label: ({ children }: { children: ReactNode }) => <ContextMenuLabel className="truncate py-1 text-2xs font-normal text-hint">{children}</ContextMenuLabel>,
  /** `reason` greys the whole submenu out (its trigger), for when none of its items could run. */
  Sub: ({ label, children, reason }: { label: string; children: ReactNode; reason?: string }) => (
    <ContextMenuSub>
      <Reason reason={reason}>
        <ContextMenuSubTrigger className={itemText} disabled={!!reason} aria-description={reason}>{label}</ContextMenuSubTrigger>
      </Reason>
      <ContextMenuSubContent>{children}</ContextMenuSubContent>
    </ContextMenuSub>
  ),
}

export const DM = {
  Content: ({ children, align = 'start' }: { children: ReactNode; align?: 'start' | 'end' | 'center' }) => (
    <DropdownMenuContent align={align} sideOffset={4} className="min-w-48 data-[state=open]:animate-none! data-[state=closed]:animate-none!">{children}</DropdownMenuContent>
  ),
  /** `reason` greys the item out and says why on hover (a tooltip, and aria-description); `title` is what an enabled item does. */
  Item: ({ children, onSelect, disabled, reason, title, testId }: { children: ReactNode; onSelect: () => void; disabled?: boolean; reason?: string; title?: string; testId?: string }) => (
    <Reason reason={reason}>
      <DropdownMenuItem className={itemText} onSelect={onSelect} disabled={disabled || !!reason} aria-description={reason} title={reason ? undefined : title} data-testid={testId}>{children}</DropdownMenuItem>
    </Reason>
  ),
  /** A toggle that keeps the menu open, so several can be flipped in a row. */
  Check: ({ children, checked, onChange, disabled, testId }: { children: ReactNode; checked: boolean; onChange: (v: boolean) => void; disabled?: boolean; testId?: string }) => (
    <DropdownMenuCheckboxItem className={itemText} checked={checked} disabled={disabled} data-testid={testId}
      onCheckedChange={(v) => onChange(v === true)} onSelect={(e) => e.preventDefault()}>
      {children}
    </DropdownMenuCheckboxItem>
  ),
  Separator: () => <DropdownMenuSeparator />,
  Label: ({ children }: { children: ReactNode }) => <DropdownMenuLabel className="py-1 text-2xs font-normal text-hint">{children}</DropdownMenuLabel>,
  Sub: ({ label, children }: { label: string; children: ReactNode }) => (
    <DropdownMenuSub>
      <DropdownMenuSubTrigger className={itemText}>{label}</DropdownMenuSubTrigger>
      <DropdownMenuSubContent className="max-h-80 overflow-y-auto">{children}</DropdownMenuSubContent>
    </DropdownMenuSub>
  ),
}

export function Modal({ open, onClose, title, children, width = 440, tall = false, onEscapeKeyDown }: {
  open: boolean; onClose: () => void; title: string; children: ReactNode; width?: number
  /** A big dialog (a whole editor): placed near the top so it has the height. */
  tall?: boolean
  /** Esc closes the dialog unless this calls preventDefault (to end something inside it first). */
  onEscapeKeyDown?: (e: KeyboardEvent) => void
}) {
  return (
    <Dialog open={open} onOpenChange={(o) => !o && onClose()}>
      <DialogContent
        showCloseButton={false}
        onEscapeKeyDown={onEscapeKeyDown}
        style={{ width }}
        // shadcn centres a dialog and caps it at sm:max-w-lg; ours sit near the top and choose their width.
        className={cn('block max-w-[94vw] translate-y-0 gap-0 p-4 sm:max-w-[94vw]', tall ? 'top-[5vh]' : 'top-[18%]')}
      >
        <DialogTitle className="mb-3 text-base leading-normal">{title}</DialogTitle>
        <DialogDescription className="sr-only">{title}</DialogDescription>
        {children}
      </DialogContent>
    </Dialog>
  )
}

export function TextField({ label, className, ...props }: InputHTMLAttributes<HTMLInputElement> & { label?: string }) {
  return (
    <label className="block">
      {label && <span className="mb-1 block text-xs text-muted-foreground">{label}</span>}
      <Input {...props} className={cn('h-input bg-background px-2 py-0 text-sm shadow-none md:text-sm dark:bg-background', className)} />
    </label>
  )
}
