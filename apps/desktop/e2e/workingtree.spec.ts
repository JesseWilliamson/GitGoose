import { makeFixture, tempDir } from '@gitgoose/fixtures'
import { execFileSync } from 'node:child_process'
import { expect, test } from '@playwright/test'
import { clickRowAction, launch } from './app'

test('stages a file, commits, and undoes the commit', async () => {
  const r = makeFixture('linear')
  r.write('notes.md', '# notes\n')
  const { app, page } = await launch(r.dir)
  await page.getByTestId('wip-row').click()
  await expect(page.getByTestId('unstaged-file')).toHaveCount(1)
  await page.getByTestId('stage-all').click()
  await expect(page.getByTestId('staged-file')).toHaveCount(1)
  await page.getByTestId('commit-summary').fill('Add notes')
  await page.getByTestId('commit-button').click()
  await expect(page.getByTestId('commit-row').first()).toContainText('Add notes')
  await expect(page.getByTestId('wip-row')).toHaveCount(0)
  expect(r.git('log', '-1', '--format=%s').trim()).toBe('Add notes')

  // Undo from the toast.
  await page.getByTestId('toast-action').filter({ hasText: 'Undo' }).first().click()
  await expect(page.getByTestId('wip-row')).toBeVisible()
  expect(r.git('log', '-1', '--format=%s').trim()).toBe('Commit 5')
  expect(r.git('diff', '--cached', '--name-only').trim()).toBe('notes.md')
  await app.close()
})

test('stages selected lines from the diff view', async () => {
  const r = makeFixture('linear')
  r.write('file.txt', 'line 5\nline 5\nKEEP ME\nline 5\nline 5\nline 5\nNOT YET\n')
  const { app, page } = await launch(r.dir)
  await page.getByTestId('wip-row').click()
  await page.getByTestId('unstaged-file').first().click()
  await expect(page.getByTestId('file-view')).toBeVisible()
  await page.getByTestId('diff-line').filter({ hasText: 'KEEP ME' }).click()
  await page.getByTestId('stage-lines').click()
  await expect(page.getByTestId('staged-file')).toHaveCount(1)
  const staged = r.git('show', ':file.txt')
  expect(staged).toContain('KEEP ME')
  expect(staged).not.toContain('NOT YET')
  await app.close()
})

test('the + in a line\'s gutter stages that line on its own; staged, it becomes a -', async () => {
  const r = makeFixture('linear')
  r.write('file.txt', 'line 5\nline 5\nKEEP ME\nline 5\nline 5\nline 5\nNOT YET\n')
  const { app, page } = await launch(r.dir)
  await page.getByTestId('wip-row').click()
  await page.getByTestId('unstaged-file').first().click()
  const keep = page.getByTestId('diff-line').filter({ hasText: 'KEEP ME' })
  // The button is the affordance that replaced the "click lines to select them" sentence: it is
  // in the gutter, it appears on hover, and one press stages that line and nothing else.
  const plus = keep.getByTestId('line-apply')
  await expect(plus).toBeHidden()
  await keep.hover()
  await expect(plus).toBeVisible()
  await plus.click()
  await expect(page.getByTestId('staged-file')).toHaveCount(1)
  const staged = r.git('show', ':file.txt')
  expect(staged).toContain('KEEP ME')
  expect(staged).not.toContain('NOT YET')

  // The same button in the staged diff takes the line back out again.
  await page.getByTestId('staged-file').first().click()
  const line = page.getByTestId('diff-line').filter({ hasText: 'KEEP ME' })
  await line.hover()
  await line.getByTestId('line-apply').click()
  await expect(page.getByTestId('staged-file')).toHaveCount(0)
  expect(r.git('show', ':file.txt')).not.toContain('KEEP ME')
  await app.close()
})

test('shift-click selects a run of files, ctrl-click adds one; staging from one of them stages them all', async () => {
  const r = makeFixture('linear')
  for (const f of ['a.txt', 'b.txt', 'c.txt', 'd.txt', 'e.txt']) r.write(f, `${f}\n`)
  const { app, page } = await launch(r.dir)
  await page.getByTestId('wip-row').click()
  const file = (name: string) => page.locator(`[data-testid="unstaged-file"][data-path="${name}"]`)
  const selected = page.locator('[data-testid="unstaged-file"][data-selected]')
  await expect(page.getByTestId('unstaged-file')).toHaveCount(5)
  await file('b.txt').click()
  await file('d.txt').click({ modifiers: ['Shift'] })
  await expect(selected).toHaveCount(3)
  await file('a.txt').click({ modifiers: ['ControlOrMeta'] })
  await expect(selected).toHaveCount(4)
  // Every action on a selected row takes the whole selection.
  await file('c.txt').click({ button: 'right' })
  await page.getByRole('menuitem', { name: 'Stage 4 files' }).click()
  await expect(page.getByTestId('staged-file')).toHaveCount(4)
  await expect(page.getByTestId('unstaged-file')).toHaveCount(1)
  expect(r.git('diff', '--cached', '--name-only').trim().split('\n')).toEqual(['a.txt', 'b.txt', 'c.txt', 'd.txt'])
  await app.close()
})

test('discards a file and brings it back with Ctrl+Z', async () => {
  const r = makeFixture('linear')
  r.write('file.txt', 'precious edit\n')
  const { app, page } = await launch(r.dir)
  await page.getByTestId('wip-row').click()
  const row = page.getByTestId('unstaged-file').first()
  await clickRowAction(page, row, 'Discard changes')
  await expect(page.getByTestId('wip-row')).toHaveCount(0)
  await page.getByTestId('graph-scroll').focus()
  await page.keyboard.press('ControlOrMeta+z')
  await expect(page.getByTestId('wip-row')).toBeVisible()
  expect(r.git('diff').includes('precious edit')).toBe(true)
  await app.close()
})

